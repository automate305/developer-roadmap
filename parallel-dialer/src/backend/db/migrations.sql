-- =============================================================================
-- Parallel Dialer — Supabase schema
-- Run once in the Supabase SQL editor (Dashboard → SQL Editor → New query).
-- Safe to re-run: every statement uses IF NOT EXISTS / ON CONFLICT DO NOTHING.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. Custom Dispositions
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS custom_dispositions (
    id          SERIAL PRIMARY KEY,
    label       VARCHAR(50) UNIQUE NOT NULL,
    requires_notes BOOLEAN DEFAULT FALSE,
    -- 'auto' dispositions skip the notes window entirely (No Answer, Busy, etc.)
    -- 'manual' dispositions open the notes/countdown modal
    category    VARCHAR(20) DEFAULT 'manual' CHECK (category IN ('auto', 'manual')),
    sort_order  INT DEFAULT 0,
    active      BOOLEAN DEFAULT TRUE,
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- Seed the default disposition set
INSERT INTO custom_dispositions (label, requires_notes, category, sort_order)
VALUES
  ('Meeting Booked',   TRUE,  'manual', 1),
  ('Interested',       TRUE,  'manual', 2),
  ('Callback',         TRUE,  'manual', 3),
  ('Not Interested',   FALSE, 'manual', 4),
  ('No Answer',        FALSE, 'auto',   5),
  ('Voicemail',        FALSE, 'auto',   6),
  ('Busy',             FALSE, 'auto',   7),
  ('Wrong Number',     FALSE, 'auto',   8),
  ('Bad Data',         FALSE, 'auto',   9),
  ('Do Not Call',      FALSE, 'manual', 10)
ON CONFLICT (label) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. Contact Lists
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contact_lists (
    id              TEXT PRIMARY KEY,     -- uuid generated by frontend (kept for compat)
    name            TEXT NOT NULL,
    count           INT DEFAULT 0,
    dialable_count  INT DEFAULT 0,
    campaign_name   TEXT DEFAULT 'General Outbound',
    imported_at     TIMESTAMPTZ DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- 3. Contacts
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contacts (
    id          TEXT PRIMARY KEY,
    list_id     TEXT REFERENCES contact_lists(id) ON DELETE CASCADE,
    phone       TEXT NOT NULL,
    name        TEXT,
    company     TEXT,
    email       TEXT,
    raw         JSONB,          -- full CSV row for any extra columns
    last_disposition TEXT,
    last_called_at   TIMESTAMPTZ,
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS contacts_list_id_idx ON contacts(list_id);
CREATE INDEX IF NOT EXISTS contacts_phone_idx   ON contacts(phone);

-- ---------------------------------------------------------------------------
-- 4. Call Logs
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS call_logs (
    id                  SERIAL PRIMARY KEY,
    session_id          TEXT NOT NULL,
    campaign_name       TEXT DEFAULT 'General Outbound',
    prospect_phone      TEXT NOT NULL,
    prospect_name       TEXT,
    prospect_company    TEXT,
    contact_id          TEXT,
    call_sid            TEXT,
    duration_seconds    INT DEFAULT 0,
    disposition         TEXT,           -- AMD verdict: HUMAN, MACHINE, NO_ANSWER, BUSY, FAILED
    agent_outcome       TEXT,           -- agent-logged: meeting, callback, not_interested, etc.
    notes               TEXT,
    amd_transcript      TEXT,
    dialed_at           TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS call_logs_session_id_idx ON call_logs(session_id);
CREATE INDEX IF NOT EXISTS call_logs_dialed_at_idx  ON call_logs(dialed_at);

-- ---------------------------------------------------------------------------
-- 5. Session Reports
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS session_reports (
    session_id          TEXT PRIMARY KEY,
    list_name           TEXT,
    campaign_name       TEXT DEFAULT 'General Outbound',
    mode                TEXT CHECK (mode IN ('power', 'parallel')),
    start_time          TIMESTAMPTZ NOT NULL,
    end_time            TIMESTAMPTZ DEFAULT NOW(),
    total_calls         INT DEFAULT 0,
    total_conversations INT DEFAULT 0,    -- HUMAN verdicts
    meetings_booked     INT DEFAULT 0,
    interested          INT DEFAULT 0,
    not_interested      INT DEFAULT 0,
    callbacks           INT DEFAULT 0,
    voicemails          INT DEFAULT 0,
    no_answer           INT DEFAULT 0,
    busy                INT DEFAULT 0,
    failed              INT DEFAULT 0,
    abandoned           INT DEFAULT 0,
    raw_kpi_payload     JSONB,
    make_webhook_sent   BOOLEAN DEFAULT FALSE,
    make_webhook_at     TIMESTAMPTZ
);

-- ---------------------------------------------------------------------------
-- 6. AMD Audit Log
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS amd_audit (
    id              BIGSERIAL PRIMARY KEY,
    session_id      TEXT,
    call_sid        TEXT,
    phone           TEXT,
    verdict         TEXT,
    confidence      NUMERIC(4,3),
    speech_ms       INT,
    silence_ms      INT,
    transcript      TEXT,
    config_snapshot JSONB,
    logged_at       TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS amd_audit_session_idx ON amd_audit(session_id);
CREATE INDEX IF NOT EXISTS amd_audit_logged_at_idx ON amd_audit(logged_at);
